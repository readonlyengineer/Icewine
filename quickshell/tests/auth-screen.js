// Native rendering/input is exercised by tests/breeze-lock.py with KDE's real QML.
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const lock = fs.readFileSync(path.join(__dirname, "../modules/LockScreenSurface.qml"), "utf8")
const session = fs.readFileSync(path.join(__dirname, "../modules/SessionControl.qml"), "utf8")
assert.match(lock, /Breeze\.SessionManagementScreen/)
assert.match(lock, /PlasmaExtras\.PasswordField/)
assert.doesNotMatch(lock, /sddm\.login|PamContext\s*\{|releaseLock|KWinVirtualKeyboard|org\.kde\.kscreenlocker/)
assert.match(lock, /root\.session\.submit\(\)/)
assert.equal((session.match(/InputPanel\s*\{/g) || []).length, 1)
for (const obsolete of ["AuthScreen.qml", "AuthModel.js"])
    assert.equal(fs.existsSync(path.join(__dirname, "../modules", obsolete)), false)
assert.equal(fs.existsSync(path.join(__dirname, "../../sddm/Main.qml")), false)
console.log("PASS: native Breeze adapter delegates to existing session authentication")
