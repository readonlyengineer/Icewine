assert.match(lock, /root\.session\.submit\(\)/)
assert.equal((session.match(/InputPanel\s*\{/g) || []).length, 1)
for (const obsolete of ["AuthScreen.qml", "AuthModel.js"])
    assert.equal(fs.existsSync(path.join(__dirname, "../modules", obsolete)), false)
